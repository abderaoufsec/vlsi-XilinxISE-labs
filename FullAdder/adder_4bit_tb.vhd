-- VHDL Test Bench for 4-Bit Adder
--
-- Inputs:
--   A = A3 A2 A1 A0
--   B = B3 B2 B1 B0
--   C_in = Carry input
--
-- Outputs:
--   S = S3 S2 S1 S0
--   C_out = Final carry
--
-- This testbench verifies important cases including:
--   * Basic addition
--   * Internal carry propagation
--   * Carry propagation between bits
--   * Carry between the two 2-bit adders
--   * Final carry output
--   * Maximum-value addition
--   * Carry input

LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
USE ieee.numeric_std.ALL;

LIBRARY UNISIM;
USE UNISIM.Vcomponents.ALL;

ENTITY adder_4bit_adder_4bit_sch_tb IS
END adder_4bit_adder_4bit_sch_tb;

ARCHITECTURE behavioral OF adder_4bit_adder_4bit_sch_tb IS

   COMPONENT adder_4bit
   PORT(
      A0    : IN  STD_LOGIC;
      C_in  : IN  STD_LOGIC;
      B0    : IN  STD_LOGIC;
      A1    : IN  STD_LOGIC;
      B1    : IN  STD_LOGIC;
      S0    : OUT STD_LOGIC;
      S1    : OUT STD_LOGIC;
      A2    : IN  STD_LOGIC;
      B2    : IN  STD_LOGIC;
      A3    : IN  STD_LOGIC;
      B3    : IN  STD_LOGIC;
      S2    : OUT STD_LOGIC;
      S3    : OUT STD_LOGIC;
      C_out : OUT STD_LOGIC
   );
   END COMPONENT;

   ------------------------------------------------------------
   -- INPUT SIGNALS
   ------------------------------------------------------------

   SIGNAL A0   : STD_LOGIC := '0';
   SIGNAL A1   : STD_LOGIC := '0';
   SIGNAL A2   : STD_LOGIC := '0';
   SIGNAL A3   : STD_LOGIC := '0';

   SIGNAL B0   : STD_LOGIC := '0';
   SIGNAL B1   : STD_LOGIC := '0';
   SIGNAL B2   : STD_LOGIC := '0';
   SIGNAL B3   : STD_LOGIC := '0';

   SIGNAL C_in : STD_LOGIC := '0';

   ------------------------------------------------------------
   -- OUTPUT SIGNALS
   ------------------------------------------------------------

   SIGNAL S0    : STD_LOGIC;
   SIGNAL S1    : STD_LOGIC;
   SIGNAL S2    : STD_LOGIC;
   SIGNAL S3    : STD_LOGIC;
   SIGNAL C_out : STD_LOGIC;

BEGIN

   ------------------------------------------------------------
   -- UNIT UNDER TEST
   ------------------------------------------------------------

   UUT: adder_4bit
   PORT MAP(
      A0    => A0,
      C_in  => C_in,
      B0    => B0,
      A1    => A1,
      B1    => B1,
      S0    => S0,
      S1    => S1,
      A2    => A2,
      B2    => B2,
      A3    => A3,
      B3    => B3,
      S2    => S2,
      S3    => S3,
      C_out => C_out
   );


   ------------------------------------------------------------
   -- TEST PROCESS
   ------------------------------------------------------------

   tb : PROCESS
   BEGIN

      ---------------------------------------------------------
      -- TEST 1
      -- 0000 + 0000 + 0 = 00000
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '0'; A1 <= '0'; A0 <= '0';
      B3 <= '0'; B2 <= '0'; B1 <= '0'; B0 <= '0';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 2
      -- 0001 + 0001 = 0010
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '0'; A1 <= '0'; A0 <= '1';
      B3 <= '0'; B2 <= '0'; B1 <= '0'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 3
      -- 0011 + 0001 = 0100
      -- Tests carry propagation
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '0'; A1 <= '1'; A0 <= '1';
      B3 <= '0'; B2 <= '0'; B1 <= '0'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 4
      -- 0111 + 0001 = 1000
      -- Tests carry propagation through several bits
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '1'; A1 <= '1'; A0 <= '1';
      B3 <= '0'; B2 <= '0'; B1 <= '0'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 5
      -- 0111 + 0111 = 1110
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '1'; A1 <= '1'; A0 <= '1';
      B3 <= '0'; B2 <= '1'; B1 <= '1'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 6
      -- 1000 + 1000 = 10000
      -- Tests final carry output
      --
      -- Expected:
      -- C_out S3 S2 S1 S0 = 10000
      ---------------------------------------------------------

      A3 <= '1'; A2 <= '0'; A1 <= '0'; A0 <= '0';
      B3 <= '1'; B2 <= '0'; B1 <= '0'; B0 <= '0';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 7
      -- 1111 + 0001 = 10000
      -- Full carry propagation
      ---------------------------------------------------------

      A3 <= '1'; A2 <= '1'; A1 <= '1'; A0 <= '1';
      B3 <= '0'; B2 <= '0'; B1 <= '0'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 8
      -- 1111 + 1111 = 11110
      --
      -- Expected:
      -- C_out S3 S2 S1 S0 = 11110
      ---------------------------------------------------------

      A3 <= '1'; A2 <= '1'; A1 <= '1'; A0 <= '1';
      B3 <= '1'; B2 <= '1'; B1 <= '1'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 9
      -- 0000 + 0000 + 1 = 00001
      -- Tests C_in
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '0'; A1 <= '0'; A0 <= '0';
      B3 <= '0'; B2 <= '0'; B1 <= '0'; B0 <= '0';
      C_in <= '1';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 10
      -- 0011 + 0011 + 1 = 00111
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '0'; A1 <= '1'; A0 <= '1';
      B3 <= '0'; B2 <= '0'; B1 <= '1'; B0 <= '1';
      C_in <= '1';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 11
      -- 0111 + 1000 = 01111
      --
      -- 7 + 8 = 15
      ---------------------------------------------------------

      A3 <= '0'; A2 <= '1'; A1 <= '1'; A0 <= '1';
      B3 <= '1'; B2 <= '0'; B1 <= '0'; B0 <= '0';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 12
      -- 1010 + 0101 = 01111
      --
      -- 10 + 5 = 15
      ---------------------------------------------------------

      A3 <= '1'; A2 <= '0'; A1 <= '1'; A0 <= '0';
      B3 <= '0'; B2 <= '1'; B1 <= '0'; B0 <= '1';
      C_in <= '0';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 13
      -- 1010 + 0101 + 1 = 10000
      --
      -- 10 + 5 + 1 = 16
      ---------------------------------------------------------

      A3 <= '1'; A2 <= '0'; A1 <= '1'; A0 <= '0';
      B3 <= '0'; B2 <= '1'; B1 <= '0'; B0 <= '1';
      C_in <= '1';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- TEST 14
      -- 1111 + 1111 + 1 = 11111
      --
      -- 15 + 15 + 1 = 31
      --
      -- Expected:
      -- C_out S3 S2 S1 S0 = 11111
      ---------------------------------------------------------

      A3 <= '1'; A2 <= '1'; A1 <= '1'; A0 <= '1';
      B3 <= '1'; B2 <= '1'; B1 <= '1'; B0 <= '1';
      C_in <= '1';
      WAIT FOR 20 ns;


      ---------------------------------------------------------
      -- END SIMULATION
      ---------------------------------------------------------

      WAIT;

   END PROCESS;

END behavioral;